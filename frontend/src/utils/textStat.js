/**
 * 正文「字数」统计（10-12-preview-draft-copy-defense R5）。
 *
 * 存在的理由：旧实现把 markdown 原文整个按非空白字符计——围栏代码、标题/强调标记、
 * 尤其是图片语法里的几十字符长的图床 URL 全被算进「字数」，插图多/链接多的文章严重虚高。
 */
/**
 * 「字数」口径（实现取舍；目标是贴近读者在预览里看到的正文长度）：
 *  - 图片语法 `![alt](target)` **整体剥离**：本系统插图 alt 通常为空、target 是图床地址，都不是读者读的「字」；
 *  - 链接 `[text](target)` 只保留链接文字（文字是内容，target 不是）；
 *  - 围栏代码块只剥 ``` / ~~~ 围栏行（含语言注记），**代码内容保留计数**——代码也是文章可读部分；
 *  - 行首列表标记（`- + *` + 空格）与引用式链接定义行 `[id]: url` 剥离；有序列表编号「1.」在预览中可见，保留计数；
 *  - 结构性标记字符 `# * _ ~ \` > | - +` 一律剥离（标题/强调/删除线/行内代码反引号/引用/表格分隔/分隔线与连字符）——
 *    连字符出现在日期（2026-10-12）里也被剥，标点不算「字」；
 *  - 最终按**非空白字符**计数（中英文混合一视同仁，与旧实现空白口径一致）。
 *
 * 已接受偏差（均为预览中真实可见的内容，计入）：
 *  - 行内 HTML 标签、autolink/裸 URL 按字符计入；
 *  - HTML 实体与转义符（如 `\*`）按字面字符计入；
 *  - 语法解析与 `utils/bodyImageRefs.js` 同为非完整 CommonMark 解析：目标中出现裸括号（`![](a(1).png)`）
 *    会在首个 `)` 截断，边界情形与插图计数器保持同一容错宽度。
 */

/** 剥离 markdown 结构性语法后统计非空白字符数。无响应式依赖的纯函数。 */
export function textStatOf(md) {
  let s = String(md || '')
  s = s.replace(/^[ \t]{0,3}(?:```+|~~~+)[^\n]*$/gm, '')                          // 围栏标记行（剥标记，保内容）
  s = s.replace(/!\[[^[\]]*(?:\[[^[\]]*\])?[^[\]]*\]\([^)]*\)/g, '')              // 图片语法整体剥离（alt 容忍一层方括号，同 bodyImageRefs 口径）
  s = s.replace(/^[ \t]{0,3}\[[^\]]*\]:[^\n]*$/gm, '')                            // 引用式链接定义行
  s = s.replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')                                   // 链接只保留链接文字
  s = s.replace(/^[ \t]*[-+*][ \t]+/gm, '')                                       // 行首列表标记
  s = s.replace(/[#*_~`>|+-]/g, '')                                               // 结构性标记字符
  return s.replace(/\s/g, '').length
}

export default { textStatOf }